export interface UiStrings {
  // 言語の確認
  ask: string;
  yes: string;
  fromPhone: string;
  language: string;
  region: string;
  dialect: string;
  notSet: string;
  details: string;
  hideDetails: string;
  phoneSetting: string;
  chooseAnother: string;
  /** 最初の画面のカードのボタン（話す言葉・伝える言葉の両方）。短くして1行に収める */
  change: string;
  whichLanguage: string;
  regionOrDialect: string;
  continue: string;
  // 共通
  step: (n: number) => string;
  back: string;
  textSize: string;
  /** 標準 / 大 / 特大 */
  sizeNames: [string, string, string];
  // 最初の画面（話す言葉・伝える言葉・年齢・性別）
  /** 話す言葉の見出し */
  youSpeak: string;
  /** 伝える言葉の見出し */
  tellIn: string;
  /** 伝える言葉が話す言葉と同じとき */
  sameLang: string;
  /** 年齢・性別を選ぶまで始められないときの案内 */
  needAgeSex: string;
  age: string;
  sex: string;
  startTalking: string;
  /** 15歳未満 / 15–29 / 30–49 / 50–69 / 70以上 */
  ages: [string, string, string, string, string];
  /** 女性 / 男性 / 答えない */
  sexes: [string, string, string];
  // 問診
  hint: string;
  /** 右上の「?」ボタンの読み上げ名。押すと hint を出す */
  hintLabel: string;
  /** AI が口述を解釈しているあいだの表示 */
  analyzing: string;
  weUnderstood: string;
  painOutOf: (n: number) => string;
  painAria: (n: number) => string;
  scaleMin: string;
  scaleMax: string;
  listening: string;
  tapToSpeak: string;
  reviewAnswers: string;
  /** 問診の質問（data/interview.ts の TURN_BASE と同じ順） */
  questions: [string, string, string, string, string, string];
  /** 確認画面の項目名（同じ順） */
  reviewKeys: [string, string, string, string, string, string];
  // 確認・完了
  reviewTitle: string;
  edit: (item: string) => string;
  /** 確認画面で項目を書き直すときの保存・取り消し */
  save: string;
  cancel: string;
  confirm: string;
  fix: string;
  doneTitle: string;
  doneBody: string;
  previewClinic: string;
  startOver: string;
}

