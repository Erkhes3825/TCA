// 聞き足しのボタンの回答・病名は、患者画面の訳（followUps.ts）をそのまま使う
const add = (ja: string, zh: string, mn: string) => { if (!(ja in DICT)) DICT[ja] = [zh, mn]; };
for (const k of Object.keys(FOLLOW_UP_TEXT.ja.opt) as OptId[]) add(FOLLOW_UP_TEXT.ja.opt[k], FOLLOW_UP_TEXT.zh.opt[k], FOLLOW_UP_TEXT.mn.opt[k]);
for (const k of ILLNESS_IDS) add(FOLLOW_UP_TEXT.ja.illness[k], FOLLOW_UP_TEXT.zh.illness[k], FOLLOW_UP_TEXT.mn.illness[k]);
UI.ja.ages.forEach((a, i) => add(a, UI.zh.ages[i], UI.mn.ages[i]));
UI.ja.sexes.forEach((x, i) => add(x, UI.zh.sexes[i], UI.mn.sexes[i]));

/** 数字が入る文言 */
const PATTERNS: [RegExp, string, string][] = [
  [/^0〜10のスケールで「(\d+)」を画面上で選択$/, '在0～10量表上选择了“$1”', '0–10 хуваарь дээр «$1» сонгосон'],
  [/^(\d+) \/ 10（0〜10の自己評価）$/, '$1 / 10（0～10自评）', '$1 / 10 (0–10 өөрийн үнэлгээ)'],
  [/^原文（(.*)）$/, '原文（$1）', 'Эх бичвэр ($1)'],
];

/** 問診票の日本語を、伝える言葉に置き換える。辞書に無いもの（AI の訳など）はそのまま */
export function tr(target: TargetLang, ja: string): string {
  if (target === 'ja') return ja;
  const i = target === 'zh' ? 0 : 1;
  const hit = DICT[ja];
  if (hit) return hit[i];
  for (const [re, zh, mn] of PATTERNS) if (re.test(ja)) return ja.replace(re, i === 0 ? zh : mn);
  return ja;
}

